def sample_webhooks() -> tuple[WebhookEvent, ...]:
    """A realistic delivery, including the three cases a handler is judged on:
    a retry, an out of order event and the same purchase arriving twice."""
    return (
        WebhookEvent("evt_1PaA01", EVENT_CHECKOUT_COMPLETED, CUSTOMER_WEB, 100),
        WebhookEvent("evt_1PaA02", EVENT_SUBSCRIPTION_CREATED, CUSTOMER_WEB, 101),
        WebhookEvent("evt_1PaA03", EVENT_INVOICE_PAID, CUSTOMER_WEB, 102),
        # Stripe did not get a 2xx in time and sent it again.
        WebhookEvent("evt_1PaA03", EVENT_INVOICE_PAID, CUSTOMER_WEB, 102),
        # An older update arriving late.
        WebhookEvent("evt_1PaA04", EVENT_SUBSCRIPTION_UPDATED, CUSTOMER_WEB, 99),
        # The in app purchase, then the same purchase reaching Stripe.
        WebhookEvent("evt_1PaB01", EVENT_SUBSCRIPTION_CREATED, CUSTOMER_APPLE,
                     200, source=SOURCE_APPLE,
                     apple_transaction_id=APPLE_TRANSACTION),
        WebhookEvent("evt_1PaB02", EVENT_INVOICE_PAID, CUSTOMER_APPLE, 201,
                     source=SOURCE_APPLE,
                     apple_transaction_id=APPLE_TRANSACTION),
    )


def replay(events: tuple[WebhookEvent, ...],
           ledger: BillingLedger | None = None) -> BillingLedger:
    target = ledger or BillingLedger()
    for event in events:
        handle_event(target, event)
    return target


