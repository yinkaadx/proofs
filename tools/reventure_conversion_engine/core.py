@dataclass(frozen=True)
class WebhookEvent:
    event_id: str            # evt_... , unique per event, repeated on retries
    type: str
    customer_id: str
    created: int             # Stripe's own ordering field
    amount_cents: int = 1499
    source: str = SOURCE_STRIPE
    apple_transaction_id: str = ""


@dataclass(frozen=True)
class LedgerEntry:
    event: WebhookEvent
    outcome: str
    status_before: str
    status_after: str
    charged_cents: int
    note: str


@dataclass
class BillingLedger:
    """What a real handler keeps: processed event ids, entitlements, and the
    Apple transaction ids already mapped to a customer."""
    seen_events: set = field(default_factory=set)
    entitlements: dict[str, dict] = field(default_factory=dict)
    apple_links: dict[str, str] = field(default_factory=dict)
    entries: list[LedgerEntry] = field(default_factory=list)

    def status_of(self, customer_id: str) -> str:
        return self.entitlements.get(customer_id, {}).get(
            "status", ENTITLEMENT_NONE)

    def charged_total(self) -> int:
        return sum(entry.charged_cents for entry in self.entries)

    def count(self, outcome: str) -> int:
        return sum(1 for entry in self.entries if entry.outcome == outcome)

    def entry_rows(self) -> list[dict]:
        return [
            {"Event id": entry.event.event_id,
             "Type": entry.event.type,
             "Customer": entry.event.customer_id,
             "Source": entry.event.source,
             "Outcome": entry.outcome,
             "Charged": f"{entry.charged_cents / 100:.2f}",
             "Entitlement": f"{entry.status_before} to {entry.status_after}"}
            for entry in self.entries
        ]

    def entitlement_rows(self) -> list[dict]:
        return [
            {"Customer": customer_id,
             "Entitlement": row.get("status", ENTITLEMENT_NONE),
             "Charged to date": f"{row.get('charged', 0) / 100:.2f}",
             "Last event": row.get("last_event", ""),
             "Apple linked": "Yes" if row.get("apple_linked") else "No"}
            for customer_id, row in sorted(self.entitlements.items())
        ]


CHARGING_EVENTS = (EVENT_INVOICE_PAID,)


def handle_event(ledger: BillingLedger, event: WebhookEvent) -> LedgerEntry:
    """Apply one webhook exactly once, and say what it did.

    Three things have to hold or somebody is charged twice. A redelivered event
    must change nothing, because Stripe retries until it gets a 2xx. An event
    that arrives after a newer one must not roll the entitlement backwards. And
    a purchase that already exists through Apple must not also be charged on
    the card, because the two systems do not know about each other.
    """
    before = ledger.status_of(event.customer_id)

    if event.event_id in ledger.seen_events:
        return _record(ledger, event, DUPLICATE, before, before, 0,
                       "Already processed. Stripe retries until the endpoint "
                       "answers with a 2xx, so the event id is the only thing "
                       "standing between a retry and a second charge.")

    row = ledger.entitlements.setdefault(
        event.customer_id, {"status": ENTITLEMENT_NONE, "charged": 0,
                            "last_created": 0, "last_event": "",
                            "apple_linked": False})

    if event.created < row["last_created"]:
        ledger.seen_events.add(event.event_id)
        return _record(ledger, event, STALE, before, before, 0,
                       f"This event was created before one already applied "
                       f"({event.created} against {row['last_created']}). "
                       f"Webhooks arrive out of order, and applying it would "
                       f"roll the entitlement backwards.")

    # Apple Pay in app purchases arrive with Apple's own transaction id. The
    # first one is linked to the customer; a second arrival of the same
    # transaction is the same purchase reaching us by another route.
    if event.apple_transaction_id:
        linked_to = ledger.apple_links.get(event.apple_transaction_id)
        if linked_to is not None and linked_to != event.customer_id:
            ledger.seen_events.add(event.event_id)
            return _record(
                ledger, event, DOUBLE_BILL_BLOCKED, before, before, 0,
                f"Apple transaction {event.apple_transaction_id} is already "
                f"linked to {linked_to}. Charging {event.customer_id} as well "
                f"would bill the same purchase twice, once through Apple and "
                f"once through Stripe.")
        if linked_to == event.customer_id and event.type in CHARGING_EVENTS:
            ledger.seen_events.add(event.event_id)
            return _record(
                ledger, event, DOUBLE_BILL_BLOCKED, before, before, 0,
                f"This subscription is already paid through Apple under "
                f"{event.apple_transaction_id}. The Stripe invoice for the "
                f"same period is not charged.")
        ledger.apple_links[event.apple_transaction_id] = event.customer_id
        row["apple_linked"] = True

    after = STATUS_AFTER[event.type]
    charged = event.amount_cents if event.type in CHARGING_EVENTS else 0

    ledger.seen_events.add(event.event_id)
    row.update({"status": after, "last_created": event.created,
                "last_event": event.event_id,
                "charged": row["charged"] + charged})

    return _record(ledger, event, APPLIED, before, after, charged,
                   f"{event.type} applied. {event.customer_id} moved from "
                   f"{before} to {after}.")


def _record(ledger: BillingLedger, event: WebhookEvent, outcome: str,
            before: str, after: str, charged: int, note: str) -> LedgerEntry:
    entry = LedgerEntry(event=event, outcome=outcome, status_before=before,
                        status_after=after, charged_cents=charged, note=note)
    ledger.entries.append(entry)
    return entry


