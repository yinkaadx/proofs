TRIGGER_APP_LAUNCH = "App launch"
TRIGGER_ONBOARDING = "Onboarding finished"
TRIGGER_SETTINGS = "Settings opened"
TRIGGER_ERROR = "Error screen shown"
TRIGGER_DEAL_SAVED = "Saved a deal that beat its asking price"
TRIGGER_DEAL_SHARED = "Shared a deal with an agent"
TRIGGERS: tuple[str, ...] = (TRIGGER_APP_LAUNCH, TRIGGER_ONBOARDING,
                             TRIGGER_SETTINGS, TRIGGER_ERROR,
                             TRIGGER_DEAL_SAVED, TRIGGER_DEAL_SHARED)

# Only these two are a high value action: the user just got something worth
# having. Everything else is either neutral or actively a bad moment to ask.
HIGH_VALUE_TRIGGERS: tuple[str, ...] = (TRIGGER_DEAL_SAVED, TRIGGER_DEAL_SHARED)

# Apple allows at most three prompts per user per 365 days and ignores the rest
# silently, which is worse than refusing: the app believes it asked.
MAX_PROMPTS_PER_YEAR = 3
COOLDOWN_DAYS = 90
MIN_SESSIONS = 3

BLOCK_NOT_HIGH_VALUE = "Not a high value moment"
BLOCK_QUOTA = "Apple's yearly quota is spent"
BLOCK_COOLDOWN = "Inside the cooldown"
BLOCK_TOO_NEW = "The user has not used the app enough yet"
BLOCK_SAME_VERSION = "Already asked on this version"
ALLOWED = "Prompt shown"


@dataclass(frozen=True)
class RatingState:
    sessions: int = 8
    prompts_this_year: int = 0
    last_prompt_day: int | None = None
    asked_on_version: bool = False
    app_version: str = "2.4.0"


@dataclass(frozen=True)
class RatingDecision:
    trigger: str
    allowed: bool
    code: str
    reason: str
    gates: list[dict] = field(default_factory=list)


def should_prompt(trigger: str, state: RatingState = RatingState(),
                  day: int = 120) -> RatingDecision:
    """Decide whether the app may ask for a rating, and say why not.

    The gate that matters most is the first one. Apple counts an attempt even
    when the system decides not to display anything, so asking on launch spends
    one of three yearly asks on a person who has not yet seen the app do
    anything worth rating. The prompt belongs after a good outcome, not before
    one.
    """
    high_value = trigger in HIGH_VALUE_TRIGGERS
    within_cooldown = (state.last_prompt_day is not None
                       and day - state.last_prompt_day < COOLDOWN_DAYS)
    quota_spent = state.prompts_this_year >= MAX_PROMPTS_PER_YEAR
    too_new = state.sessions < MIN_SESSIONS

    gates = [
        {"Gate": "High value action", "Required": "Yes",
         "Actual": "Yes" if high_value else "No",
         "Status": "Pass" if high_value else "Block"},
        {"Gate": "Sessions before asking",
         "Required": f"{MIN_SESSIONS} or more",
         "Actual": str(state.sessions),
         "Status": "Block" if too_new else "Pass"},
        {"Gate": "Prompts used this year",
         "Required": f"Under {MAX_PROMPTS_PER_YEAR}",
         "Actual": str(state.prompts_this_year),
         "Status": "Block" if quota_spent else "Pass"},
        {"Gate": "Days since the last prompt",
         "Required": f"{COOLDOWN_DAYS} or more",
         "Actual": ("never asked" if state.last_prompt_day is None
                    else str(day - state.last_prompt_day)),
         "Status": "Block" if within_cooldown else "Pass"},
        {"Gate": "Already asked on this version", "Required": "No",
         "Actual": "Yes" if state.asked_on_version else "No",
         "Status": "Block" if state.asked_on_version else "Pass"},
    ]

    if not high_value:
        return RatingDecision(
            trigger, False, BLOCK_NOT_HIGH_VALUE,
            f"{trigger} is not a moment worth asking on. Apple counts the "
            f"attempt whether or not anything is displayed, so asking here "
            f"spends one of {MAX_PROMPTS_PER_YEAR} yearly asks on a user who "
            f"has not yet seen the app do anything for them.",
            gates)
    if too_new:
        return RatingDecision(
            trigger, False, BLOCK_TOO_NEW,
            f"Only {state.sessions} session(s) so far. Below {MIN_SESSIONS} "
            f"there is not enough experience to rate, and an early ask is what "
            f"produces a one star review about being asked.",
            gates)
    if quota_spent:
        return RatingDecision(
            trigger, False, BLOCK_QUOTA,
            f"{state.prompts_this_year} prompts already shown in the last 365 "
            f"days. Apple silently shows nothing beyond "
            f"{MAX_PROMPTS_PER_YEAR}, so the app would believe it asked and no "
            f"dialog would appear.",
            gates)
    if within_cooldown:
        return RatingDecision(
            trigger, False, BLOCK_COOLDOWN,
            f"Last asked {day - state.last_prompt_day} day(s) ago and the "
            f"cooldown is {COOLDOWN_DAYS}. Asking again this soon is how the "
            f"remaining asks get wasted on the same person.",
            gates)
    if state.asked_on_version:
        return RatingDecision(
            trigger, False, BLOCK_SAME_VERSION,
            f"Already asked on version {state.app_version}. One ask per "
            f"version keeps the prompt tied to something that changed.",
            gates)

    return RatingDecision(
        trigger, True, ALLOWED,
        f"{trigger} is a high value moment, the user has {state.sessions} "
        f"sessions, and {state.prompts_this_year} of "
        f"{MAX_PROMPTS_PER_YEAR} asks have been used. "
        f"SKStoreReviewController.requestReview is called here.",
        gates)


def record_prompt(state: RatingState, day: int) -> RatingState:
    """The state after a prompt is actually shown."""
    return RatingState(sessions=state.sessions,
                       prompts_this_year=state.prompts_this_year + 1,
                       last_prompt_day=day, asked_on_version=True,
                       app_version=state.app_version)


