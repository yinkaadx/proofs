@dataclass(frozen=True)
class Recommendation:
    verdict: str
    confident: bool
    headline: str
    reasoning: list[str]
    next_step: str
    monthly_revenue_delta: float


def recommend(result: TestResult, flag: FeatureFlag,
              price: float = MONTHLY_PRICE,
              monthly_users: int = 40_000) -> Recommendation:
    """Turn the statistics into a decision, with the reasoning shown.

    Computed from the numbers rather than generated, deliberately. A real
    deployment would hand these same figures to Claude for the write up; doing
    the arithmetic here means the recommendation cannot contradict the table it
    is describing, which is the failure mode that matters when somebody ships
    on the strength of a paragraph.
    """
    control, treatment = result.control, result.treatment
    per_user_delta = (treatment.conversion_rate - control.conversion_rate) * price
    revenue_delta = round(per_user_delta * monthly_users, 2)

    reasoning = [
        f"Control converted {control.paid} of {control.users} exposed users "
        f"at {control.conversion_rate:.2%}. The Pro paywall converted "
        f"{treatment.paid} of {treatment.users} at "
        f"{treatment.conversion_rate:.2%}.",
        f"That is a relative lift of {result.lift:+.1%}, an absolute "
        f"difference of {result.absolute_difference:+.2%}.",
        f"Two proportion z test: z of {result.z_score:.2f}, p of "
        f"{result.p_value:.4f}. The 95 percent interval on the difference "
        f"runs {result.confidence_low:+.2%} to {result.confidence_high:+.2%}.",
        f"Detecting a {result.minimum_detectable_effect:.0%} relative lift at "
        f"80 percent power needs about {result.required_per_arm:,} users per "
        f"arm, and the smaller arm has "
        f"{min(control.users, treatment.users):,}.",
        f"Trial starts moved from {control.trial_rate:.1%} to "
        f"{treatment.trial_rate:.1%}, so the paywall is filtering rather than "
        f"widening the funnel.",
    ]

    if result.days_running < MIN_DAYS:
        return Recommendation(
            TOO_EARLY, False,
            f"Only {result.days_running} day(s) of data. Weekday and weekend "
            f"buyers behave differently, so a test read before a full week is "
            f"reading the calendar rather than the paywall.",
            reasoning,
            f"Leave the flag at {flag.rollout_percent} percent and read it "
            f"again after {MIN_DAYS} days.",
            revenue_delta)

    if result.significant and result.absolute_difference > 0:
        if not result.powered:
            reasoning.append(
                "The arms are smaller than the planning calculation wanted. "
                "The result still stands, and the measured lift is probably "
                "flattering: a difference that clears significance early tends "
                "to be the high end of the range. Plan on the low end of the "
                "interval rather than the point estimate.")
        return Recommendation(
            SHIP, True,
            f"The Pro paywall wins. p of {result.p_value:.4f} against a "
            f"{result.lift:+.1%} lift, and the whole confidence interval sits "
            f"above zero.",
            reasoning,
            f"Raise the flag from {flag.rollout_percent} to 50 percent for a "
            f"day, watch for crashes and refunds rather than conversion, then "
            f"go to 100. Worth about {revenue_delta:,.0f} a month at "
            f"{monthly_users:,} users.",
            revenue_delta)

    if result.significant and result.absolute_difference < 0:
        return Recommendation(
            ROLL_BACK, True,
            f"The Pro paywall converts worse, and the result is real: p of "
            f"{result.p_value:.4f} on a {result.lift:+.1%} change.",
            reasoning,
            f"Set the flag to 0 percent now. Leaving it costs about "
            f"{abs(revenue_delta):,.0f} a month.",
            revenue_delta)

    if not result.powered:
        shortfall = max(0, result.required_per_arm
                        - min(control.users, treatment.users))
        return Recommendation(
            MORE_DATA, False,
            f"No result yet. p of {result.p_value:.4f}, and the arms are "
            f"smaller than this difference needs.",
            reasoning,
            f"Keep the flag where it is and collect roughly {shortfall:,} more "
            f"users per arm before reading it again. Shipping on this would be "
            f"shipping on noise.",
            revenue_delta)

    return Recommendation(
        HOLD, True,
        f"The two paywalls perform the same. p of {result.p_value:.4f} with "
        f"arms large enough to have found a real difference.",
        reasoning,
        "Keep the current paywall. A change that does nothing still costs "
        "review time and a migration, so it is not free to ship.",
        revenue_delta)
