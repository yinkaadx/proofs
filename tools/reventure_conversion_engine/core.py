"""Mobile conversion and release engine.

Three things decide whether a React Native release makes money or costs it: the
flag that decides who sees the paywall, the moment the app asks for a rating,
and the webhook pipeline that turns a payment into an entitlement exactly once.
Each has a failure that is invisible in testing and expensive in production.

  A flag rolled to everyone on a result that was noise ships a paywall that
  converts worse than the one it replaced. A rating prompt fired on launch
  burns one of the three asks Apple allows in a year on somebody who has not
  yet seen anything good. A webhook handled twice charges a card twice, and
  the customer finds that before the dashboard does.

So the statistics are computed rather than asserted, the rating gates are
enforced rather than documented, and the webhook ledger is keyed on the event
id the way a real handler has to be.

Pure logic, no Streamlit import, so this is unit testable on its own and can sit
behind the real webhook endpoint. Deterministic: nothing here reads the clock or
a random source. Bucketing is hashed from the user id, which is how a real
assignment stays stable across sessions.
"""

from __future__ import annotations

import hashlib
import math
from dataclasses import dataclass, field

ENGINE_VERSION = "1.0.0"

APP_NAME = "Reventure"


# ---------------------------------------------------------------------------
# Feature flags and bucketing
# ---------------------------------------------------------------------------

CONTROL = "control"
TREATMENT = "treatment"
VARIANTS: tuple[str, ...] = (CONTROL, TREATMENT)

FLAG_PRO_PAYWALL = "pro_paywall"


@dataclass(frozen=True)
class FeatureFlag:
    key: str
    label: str
    enabled: bool
    rollout_percent: int
    description: str

    def __post_init__(self) -> None:
        if not 0 <= self.rollout_percent <= 100:
            raise ValueError("A rollout percentage runs from 0 to 100.")


def bucket_of(user_id: str, flag_key: str) -> int:
    """Which of a hundred buckets a user falls in, stably.

    Hashed from the user id and the flag key together, so a user keeps the same
    bucket across sessions and devices, and two flags do not assign the same
    people to treatment. Random assignment per session would let one person see
    the paywall appear and disappear, which reads as a bug and poisons the
    measurement.
    """
    digest = hashlib.sha256(f"{flag_key}:{user_id}".encode("utf-8")).hexdigest()
    return int(digest[:8], 16) % 100


def variant_for(user_id: str, flag: FeatureFlag) -> str:
    if not flag.enabled:
        return CONTROL
    return TREATMENT if bucket_of(user_id, flag.key) < flag.rollout_percent \
        else CONTROL


def exposure_split(user_ids: list[str], flag: FeatureFlag) -> dict[str, int]:
    counts = {CONTROL: 0, TREATMENT: 0}
    for user_id in user_ids:
        counts[variant_for(user_id, flag)] += 1
    return counts


def sample_user_ids(count: int = 2000) -> list[str]:
    """A stable set of user ids. Generated by rule rather than randomly, so the
    exposure split is reproducible in a test and on screen."""
    if count < 0:
        raise ValueError("A user count cannot be negative.")
    return [f"usr_{index:06d}" for index in range(count)]


